import os
import re
from contextlib import contextmanager

import psycopg

DATABASE_URL = os.environ.get("DATABASE_URL") or os.environ.get("POSTGRES_URL") or os.environ.get("POSTGRES_PRISMA_URL")

class CompatRow:
    __slots__ = ("_values", "_mapping")
    def __init__(self, values, description):
        self._values = tuple(values)
        self._mapping = {d[0]: self._values[i] for i, d in enumerate(description)}
    def __getitem__(self, key):
        return self._values[key] if isinstance(key, int) else self._mapping[key]
    def __iter__(self):
        return iter(self._values)
    def __len__(self):
        return len(self._values)
    def keys(self):
        return self._mapping.keys()

class CompatCursor:
    def __init__(self, cur):
        self._cur = cur
    @property
    def rowcount(self):
        return self._cur.rowcount
    @property
    def lastrowid(self):
        return None
    def _wrap(self, row):
        return None if row is None else CompatRow(row, self._cur.description)
    def fetchone(self):
        return self._wrap(self._cur.fetchone())
    def fetchall(self):
        return [self._wrap(r) for r in self._cur.fetchall()]
    def __iter__(self):
        for r in self._cur:
            yield self._wrap(r)
    def close(self):
        self._cur.close()

class _NullCursor:
    rowcount = -1
    description = []
    def fetchone(self): return None
    def fetchall(self): return []
    def close(self): pass
    def __iter__(self): return iter(())

class CompatConnection:
    def __init__(self, conn):
        self._conn = conn
        self.row_factory = None

    def _translate(self, sql):
        original = sql.strip()
        if original.upper().startswith("PRAGMA "):
            return None
        s = original.replace("?", "%s")
        s = re.sub(r"ALTER\\s+TABLE\\s+(\\w+)\\s+ADD\\s+COLUMN\\s+",
                   r"ALTER TABLE \\1 ADD COLUMN IF NOT EXISTS ", s, flags=re.I)
        s = re.sub(r"INTEGER\\s+PRIMARY\\s+KEY\\s+AUTOINCREMENT",
                   "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", s, flags=re.I)

        if re.match(r"^INSERT\\s+OR\\s+IGNORE\\s+", original, re.I):
            s = re.sub(r"^INSERT\\s+OR\\s+IGNORE\\s+", "INSERT ", s, flags=re.I)
            s += " ON CONFLICT DO NOTHING"

        m = re.match(r"^INSERT\\s+OR\\s+REPLACE\\s+INTO\\s+([\\w.]+)\\s*\\((.*?)\\)\\s*(.*)$",
                     original, re.I | re.S)
        if m:
            table, cols, tail = m.groups()
            col_list = [c.strip().strip('"') for c in cols.split(",")]
            s = f"INSERT INTO {table} ({cols}) {tail} ON CONFLICT DO UPDATE SET " + ", ".join(
                f"{c}=EXCLUDED.{c}" for c in col_list
            )
            s = s.replace("?", "%s")

        s = re.sub(r"([A-Za-z_][A-Za-z0-9_]*)\\s+COLLATE\\s+NOCASE",
                   r"LOWER(\\1)", s, flags=re.I)
        return s

    def execute(self, sql, params=None):
        translated = self._translate(sql)
        if translated is None:
            return CompatCursor(_NullCursor())
        cur = self._conn.cursor()
        cur.execute(translated, params or None)
        return CompatCursor(cur)

    def executemany(self, sql, seq):
        translated = self._translate(sql)
        if translated is None:
            return CompatCursor(_NullCursor())
        cur = self._conn.cursor()
        cur.executemany(translated, seq)
        return CompatCursor(cur)

    def executescript(self, script):
        for statement in script.split(";"):
            statement = statement.strip()
            if statement:
                self.execute(statement)

    def commit(self):
        self._conn.commit()
    def rollback(self):
        self._conn.rollback()
    def close(self):
        self._conn.close()
    def __enter__(self):
        return self
    def __exit__(self, exc_type, exc, tb):
        if exc_type:
            self.rollback()
        else:
            self.commit()
        self.close()

def connect():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is not configured")
    return CompatConnection(psycopg.connect(DATABASE_URL, connect_timeout=10))

@contextmanager
def db():
    conn = connect()
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()
